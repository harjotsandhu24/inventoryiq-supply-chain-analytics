"""Generate docs/results.md from the pipeline's report files (no hand-typed numbers).

Usage: python scripts/build_results_md.py [m5|synthetic]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
LABEL = {
    "seasonal_naive": "Seasonal naive",
    "moving_average": "Moving average",
    "seasonal_ma": "Seasonal moving average",
    "sba": "Croston-SBA",
    "gbm": "Gradient boosting",
    "selected": "**Selected per series**",
}


def pct(x, d=1):
    return "n/a" if pd.isna(x) else f"{x * 100:.{d}f}%"


def money(x):
    return f"${x:,.0f}"


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = [
        "| " + " | ".join(cols) + " |",
        "|" + "|".join("---" if i == 0 else "---:" for i in range(len(cols))) + "|",
    ]
    out += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(out)


def main(source: str = "m5") -> None:
    rep = ROOT / "reports" / source
    v = json.loads((rep / "data_validation.json").read_text())["summary"]
    hold = pd.read_csv(rep / "forecast_holdout_by_method_model_stores.csv")
    hold_all = pd.read_csv(rep / "forecast_holdout_by_method_all.csv")
    val = pd.read_csv(rep / "forecast_validation_by_method_model_stores.csv")
    cov = pd.read_csv(rep / "forecast_interval_coverage_model_stores.csv")
    covp = pd.read_csv(rep / "forecast_interval_coverage_by_pattern.csv")
    pat = pd.read_csv(rep / "forecast_holdout_by_pattern_model_stores.csv")
    sim = pd.read_csv(rep / "simulation_summary.csv")
    sens = pd.read_csv(rep / "simulation_sensitivity.csv")
    scen = pd.read_csv(rep / "scenario_summary.csv")
    integ = json.loads((rep / "integrity_checks.json").read_text())
    excel = rep / "excel_validation.json"

    def acc(df):
        d = df.copy()
        d["order"] = d["wape"]
        d = d.sort_values("order")
        return table(
            pd.DataFrame(
                {
                    "Method": d["method"].map(LABEL),
                    "MAE (units/day)": d["mae"].map(lambda x: f"{x:.3f}"),
                    "WAPE": d["wape"].map(pct),
                    "Bias": d["bias"].map(pct),
                    "MASE": d["mase"].map(lambda x: f"{x:.3f}"),
                }
            )
        )

    lines = [
        "# Validated results",
        "",
        f"Generated by `scripts/build_results_md.py` from `reports/{source}/`. Source: **{source.upper()}**. "
        "Forecast results use observed sales; inventory and cost results are **simulated**.",
        "",
        "## Data",
        "",
        f"- {v['series']:,} product-store series ({v['items']:,} items x {len(v['stores'])} stores), "
        f"{v['observed_days']:,} observed days ({v['first_date']} to {v['last_observed_date']}), {v['total_units']:,} recorded units.",
        f"- Validation: {v['errors']} blocking errors, {v['warnings']} flagged warnings (see `reports/{source}/data_validation.md`).",
        f"- Database integrity checks: {sum(1 for c in integ if c['violations'] == 0)}/{len(integ)} passed.",
        f"- Holdout: {v['holdout']['start_date']} to {v['holdout']['end_date']} (never used for selection or tuning).",
        "",
        "## Evidence status",
        "",
        "| Result | Status |",
        "|---|---|",
        "| Forecast accuracy, holdout d_1914-d_1941 | **Untouched holdout.** Methods, parameters and per-series selection were fixed on validation folds first; no forecasting change was made after the holdout was scored. Selection is reproducible from validation errors alone (release audit). |",
        "| Forecast accuracy, validation folds | Development data, used for tuning and selection |",
        "| Simulation, v1 in the development window | Genuine first test of a pre-specified policy |",
        "| Simulation, v2 in the development window | **Not independent.** v2 was designed after seeing v1 fail in this window. |",
        "| Simulation, v2 in the confirmation window | Out-of-sample check of v2: the window was excluded from the redesign and evaluated once. It is earlier in time, not a future period. |",
        "| All costs and the simulated stock | Depend on simulated assumptions. See the break-even analysis below. |",
        "",
        "## Forecast accuracy on the 28-day holdout",
        "",
        "### Model stores (CA_1, CA_2; all series, all five methods)",
        "",
        acc(hold),
        "",
        "### All ten stores (baselines only; gradient boosting not trained outside the model stores)",
        "",
        acc(hold_all),
        "",
        "### Validation folds (five 28-day windows before the holdout; used for selection)",
        "",
        acc(val),
        "",
        "### Holdout accuracy by demand pattern (model stores)",
        "",
        table(
            pat[pat["method"].isin(["selected", "seasonal_naive"])]
            .assign(
                Method=lambda d: d["method"].map(LABEL),
                Pattern=lambda d: d["pattern"],
                WAPE=lambda d: d["wape"].map(pct),
                MASE=lambda d: d["mase"].map(lambda x: f"{x:.3f}"),
            )[["Pattern", "Method", "WAPE", "MASE"]]
            .sort_values(["Pattern", "Method"])
        ),
        "",
        "### Prediction-interval coverage on the holdout (nominal 80% / 95%)",
        "",
        table(
            pd.DataFrame(
                {
                    "Method": cov["method"].map(LABEL),
                    "80% interval": cov["coverage80"].map(pct),
                    "95% interval": cov["coverage95"].map(pct),
                }
            )
        ),
        "",
        table(
            pd.DataFrame(
                {
                    "Pattern (selected method)": covp["pattern"],
                    "80% interval": covp["coverage80"].map(pct),
                    "95% interval": covp["coverage95"].map(pct),
                    "Days": covp["days"].map(lambda x: f"{int(x):,}"),
                }
            )
        ),
        "",
        "## Historical inventory simulation (182 days per window, simulated inventory)",
        "",
        "Policies: **basic** (status-quo min/max rule), **v1** (pre-specified forecast policy), and **v2** (v1 plus a 28-day lot cap, revised after v1).",
        "",
    ]
    for (window, scope), g in sim.groupby(["window", "scope"], sort=False):
        g = g.set_index("policy").loc[["basic", "forecast_v1", "forecast"]].reset_index()
        title = {
            "main": "Development window",
            "confirmation": "Confirmation window (held out from the v2 design)",
        }[window]
        lines += [
            f"### {title}, days {int(g['window_start_day'].iloc[0])}-{int(g['window_end_day'].iloc[0])}, scope: {scope} ({int(g['lines'].iloc[0]):,} lines)",
            "",
        ]
        lines.append(
            table(
                pd.DataFrame(
                    {
                        "Policy": g["policy_label"],
                        "Fill rate": g["fill_rate"].map(lambda x: pct(x, 2)),
                        "Cycle service": g["cycle_service_level"].map(pct),
                        "Lost units": g["lost_units"].map(lambda x: f"{x:,.0f}"),
                        "Avg inventory": g["avg_inventory_value"].map(money),
                        "PO lines": g["purchase_orders"].map(lambda x: f"{x:,}"),
                        "Holding": g["holding_cost"].map(money),
                        "Ordering": g["ordering_cost"].map(money),
                        "Shortage": g["shortage_penalty"].map(money),
                        "Modeled cost": g["modeled_total_cost"].map(money),
                    }
                )
            )
        )
        lines.append("")
    s = sens[
        (sens["margin_shift"] == 0)
        & (sens["shortage_multiplier"] == 1.5)
        & (sens["scope"] == "model_stores")
    ]
    piv = s.pivot_table(
        index=["window", "order_cost_multiplier"], columns="policy", values="modeled_total_cost"
    ).reset_index()
    audit_path = rep / "release_audit.json"
    if audit_path.exists():
        audit = json.loads(audit_path.read_text())
        cs = audit["cost_sensitivity"]
        lines += [
            "### Break-even ordering cost (v2 vs basic)",
            "",
            "Every modeled cost component is linear in its own assumption, with decisions held fixed. v2 - basic = holding difference + ordering difference + shortage difference. v2 is cheaper only above the break-even share of the assumed $4-$9 per purchase-order line.",
            "",
            table(
                pd.DataFrame(
                    [
                        {
                            "Window / scope": k.replace("main", "development"),
                            "Holding diff": money(v["v2_minus_basic_by_component"]["holding"]),
                            "Ordering diff": money(v["v2_minus_basic_by_component"]["ordering"]),
                            "Shortage diff": money(v["v2_minus_basic_by_component"]["shortage"]),
                            "Break-even (x assumed order cost)": f"{v['break_even_order_cost_multiplier']:.2f}",
                            "Break-even $/line": f"${v['break_even_order_cost_per_line_usd_range'][0]:.2f}-${v['break_even_order_cost_per_line_usd_range'][1]:.2f}",
                            "v2 cheaper in sensitivity grid": pct(v["v2_cheaper_share_of_grid"], 0),
                        }
                        for k, v in sorted(cs.items())
                    ]
                )
            ),
            "",
            "The grid covers order cost x0.1-1.0, holding rate x0.5-2.0 and shortage penalty x0.5-2.0 (60 combinations).",
            "",
        ]
    lines += [
        "### Sensitivity: modeled cost vs assumed order cost per PO line (model stores)",
        "",
        table(
            pd.DataFrame(
                {
                    "Window": piv["window"],
                    "Order cost x": piv["order_cost_multiplier"],
                    "Basic": piv["basic"].map(money),
                    "Forecast v1": piv["forecast_v1"].map(money),
                    "Forecast v2": piv["forecast"].map(money),
                }
            )
        ),
        "",
        "## Planning snapshot scenarios (demo scope, Python reference engine)",
        "",
        table(
            pd.DataFrame(
                {
                    "Scenario": scen["scenario_id"],
                    "Service level": scen["service_level"].map(lambda x: pct(x, 1)),
                    "Review (d)": scen["review_period"],
                    "Budget": scen["budget"].map(lambda x: "none" if pd.isna(x) else money(x)),
                    "Lines ordered": scen["lines_funded"],
                    "Deferred": scen["lines_deferred"],
                    "Spend": scen["purchase_spend"].map(money),
                    "High risk": scen["high_risk"],
                    "Exp. short after order": scen["expected_short_units"].map(
                        lambda x: f"{x:,.1f}"
                    ),
                    "Annual modeled cost": scen["annual_total_cost"].map(money),
                }
            )
        ),
        "",
    ]
    if excel.exists():
        e = json.loads(excel.read_text())
        lines += [
            "## Excel workbook validation",
            "",
            f"- {e['lines']} lines recalculated with the `formulas` engine; max |reorder point difference| vs Python = {e['max_abs_rop_diff']:.2e}; "
            f"quantity mismatches = {len(e['recommended_qty_mismatches'])}; ABC/XYZ mismatches = {e['abc_xyz_mismatches']}; "
            f"formula errors = {e['formula_errors']}; purchase totals Excel {money(e['purchase_total_excel'])} vs Python {money(e['purchase_total_python'])}.",
            "",
        ]
    if audit_path.exists():
        f = audit["forecast"]
        sel = f["selection_reproducible_from_validation_only"]
        conf = audit["confirmation_window"]["comparison"]
        main_ok = all(
            x["match"]
            for k, v in audit["simulation"].items()
            if not k.endswith("recomputed") and isinstance(v, list)
            for x in v
        )
        inv = audit["simulation"]["ledger_invariants"]
        lines += [
            "## Independent verification (release audit)",
            "",
            "`scripts/release_audit.py` recomputes the published numbers by a separate route:",
            "",
            f"- **Forecast holdout:** recomputed in SQL from `forecast_results` x `daily_sales`; all six methods match the report: **{f['all_match']}**.",
            f"- **Selection:** rebuilt from validation errors only, for {sel['series']:,} series; holdout forecast days that disagree: **{sel['mismatched_days']}**.",
            f"- **Development-window simulation:** recomputed in SQL from the stored daily ledger and purchase orders; all policies and scopes match: **{main_ok}**.",
            f"- **Ledger invariants:** {inv['rows']:,} rows; balance violations {inv['balance_violations']}, demand-split violations {inv['demand_split_violations']}, negative stock {inv['negative_stock']}.",
            f"- **Confirmation window:** re-executed deterministically and re-aggregated in SQL; matches: **{all(x['match'] for x in conf)}**. Its ledger is not stored, so this check uses the same simulation code, re-run.",
            "",
        ]
    out = ROOT / "docs" / ("results.md" if source == "m5" else f"results_{source}.md")
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "m5")
