"""Audit every file git would publish for M5-derived content (data-use terms).

Classifies each publishable file as:
  OK        - original code/docs, or synthetic data
  AGGREGATE - M5-derived summary statistics only (no product-level rows)
  REVIEW    - contains M5 product identifiers or images/media of M5 data: needs a manual decision
  BLOCK     - row-level M5 data that must not be published (should never appear; .gitignore prevents it)

Usage: python scripts/publication_audit.py   (writes docs/publication_audit.md, exits 1 if anything is BLOCK)
"""

from __future__ import annotations

import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
M5_ID = re.compile(r"(?<![A-Z_])(?:FOODS|HOBBIES|HOUSEHOLD)_[123]_\d{3}(?:_(?:CA|TX|WI)_\d)?")
MEDIA = {".png", ".jpg", ".jpeg", ".gif", ".webm", ".mp4"}
BINARY_DATA = {".xlsx", ".duckdb", ".parquet", ".npy"}
TEXT = {
    ".py",
    ".md",
    ".ts",
    ".tsx",
    ".mjs",
    ".json",
    ".csv",
    ".sql",
    ".toml",
    ".txt",
    ".yml",
    ".yaml",
    ".css",
    ".pq",
    ".ps1",
    "",
}


def synthetic_media_hashes() -> set[str]:
    """Hashes of images and videos whose provenance manifest says they show synthetic data."""
    hashes: set[str] = set()
    for m in ROOT.glob("**/*.manifest.json"):
        if "node_modules" in m.parts or "private" in m.parts:
            continue
        d = json.loads(m.read_text(encoding="utf-8"))
        if d.get("dataSource") != "synthetic":
            continue
        hashes.update(d.get("files", {}).values())
        if "sha256" in d:
            hashes.add(d["sha256"])
    return hashes


def publishable() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return sorted(f for f in out.splitlines() if f)


def classify(rel: str) -> tuple[str, str]:
    p = ROOT / rel
    ext = p.suffix.lower()
    if rel.startswith(("data/raw", "app/public/data", "deliverables/m5")) or ext in {
        ".duckdb",
        ".parquet",
        ".npy",
    }:
        return "BLOCK", "row-level M5 data location"
    if ext in MEDIA:
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        if digest in synthetic_media_hashes():
            return "OK", "verified synthetic capture (hash in a provenance manifest)"
        return "REVIEW", "media without synthetic provenance: may show M5 data"
    if ext == ".xlsx":
        import zipfile

        with zipfile.ZipFile(p) as z:  # scan every XML part (openpyxl writes inline strings)
            text = "".join(
                z.read(n).decode("utf-8", "ignore") for n in z.namelist() if n.endswith(".xml")
            )
        if "SYN_" in text and not M5_ID.search(text):
            return "OK", "synthetic sample workbook"
        return "BLOCK", "workbook contains M5 product ids"
    if ext in TEXT or p.name in {"LICENSE", ".gitignore"}:
        try:
            text = p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            return "REVIEW", "unreadable"
        ids = sorted(set(M5_ID.findall(text)))
        if rel.startswith("reports/m5/"):
            return (
                ("REVIEW", f"aggregate report but mentions product ids: {ids[:5]}")
                if ids
                else ("AGGREGATE", "summary statistics only")
            )
        if rel == "docs/results.md":
            return (
                ("REVIEW", f"mentions product ids {ids[:5]}")
                if ids
                else ("AGGREGATE", "summary statistics only")
            )
        if ids:
            return (
                "REVIEW",
                f"mentions M5 product ids: {', '.join(ids[:6])}{' ...' if len(ids) > 6 else ''}",
            )
        return "OK", "original code/docs or synthetic data"
    if ext in BINARY_DATA:
        return "BLOCK", "binary data file"
    return "OK", "other"


def main() -> None:
    rows = [(f, *classify(f)) for f in publishable()]
    counts: dict[str, int] = {}
    for _, c, _ in rows:
        counts[c] = counts.get(c, 0) + 1
    lines = (
        [
            "# Publication audit (M5 data-use terms)",
            "",
            "Generated by `scripts/publication_audit.py` from the files git would publish (`git ls-files --cached --others --exclude-standard`).",
            "",
            "| Class | Files |",
            "|---|---:|",
        ]
        + [f"| {k} | {v} |" for k, v in sorted(counts.items())]
        + [
            "",
            "## Files needing a manual decision or aggregate review",
            "",
            "| File | Class | Reason |",
            "|---|---|---|",
        ]
    )
    for f, c, why in rows:
        if c != "OK":
            lines.append(f"| `{f}` | {c} | {why} |")
    lines += ["", "All other files are original code and documentation, or synthetic data.", ""]
    (ROOT / "docs" / "publication_audit.md").write_text("\n".join(lines), encoding="utf-8")
    total = sum((ROOT / f).stat().st_size for f, _, _ in rows)
    manifest = [
        "# Public file manifest",
        "",
        f"Files that `git add -A` would stage at the last audit: {len(rows)} files, "
        f"{total / 1e6:.1f} MB uncompressed. Regenerate with `python scripts/publication_audit.py`.",
        "",
        "| File | Bytes | Class |",
        "|---|---:|---|",
    ] + [f"| `{f}` | {(ROOT / f).stat().st_size:,} | {c} |" for f, c, _ in rows]
    (ROOT / "docs" / "public_file_manifest.md").write_text(
        "\n".join(manifest) + "\n", encoding="utf-8"
    )
    print("\n".join(lines))
    sys.exit(1 if counts.get("BLOCK") else 0)


if __name__ == "__main__":
    main()
